// The game's text culture as an index of kCultures, by ui/text/culture.lua's rules: a name of kCultures gives itself.
// Else the leading ASCII letters are the language (none: en), then an optional "-" and the rest, both read without
// case: zh gives zh-Hant on a rest holding HANT or on TW, HK or MO, else zh-Hans; en gives en on an empty rest or US,
// else en-GB; es gives es on an empty rest or ES, else es-MX; pt gives pt-BR on BR, else pt; nb and nn give no; any
// other language of kCultures gives itself; the rest give en. name: an FString's characters, num: its count with the
// NUL (0 and a null name when empty).
inline size_t culture(const char16_t *name, int32_t num) {
  // Lua's lower and upper in the C locale change ASCII letters only, so only they are compared without case.
  const auto same = [](std::u16string_view a, std::u16string_view b) {
    const auto fold = [](char16_t c) { return c >= u'A' && c <= u'Z' ? char16_t(c + 32) : c; };
    if (a.size() != b.size())
      return false;
    for (size_t i = 0; i < a.size(); ++i)
      if (fold(a[i]) != fold(b[i]))
        return false;
    return true;
  };
  const auto index = [](std::u16string_view c) {
    size_t i = 0;
    while (i < kCultureCount && c != kCultures[i])
      ++i;
    return i;
  };
  std::u16string_view s = name && num > 1 ? std::u16string_view(name, size_t(num) - 1) : std::u16string_view();
  s = s.substr(0, s.find(u'\0'));
  if (index(s) < kCultureCount)
    return index(s);
  size_t n = 0;
  while (n < s.size() && ((s[n] >= u'a' && s[n] <= u'z') || (s[n] >= u'A' && s[n] <= u'Z')))
    ++n;
  const std::u16string_view lang = s.substr(0, n), rest = s.substr(n < s.size() && s[n] == u'-' ? n + 1 : n);
  if (same(lang, u"zh")) {
    bool hant = same(rest, u"TW") || same(rest, u"HK") || same(rest, u"MO");
    for (size_t i = 0; !hant && i + 4 <= rest.size(); ++i)
      hant = same(rest.substr(i, 4), u"HANT");
    return index(hant ? u"zh-Hant" : u"zh-Hans");
  }
  if (same(lang, u"en"))
    return index(rest.empty() || same(rest, u"US") ? u"en" : u"en-GB");
  if (same(lang, u"es"))
    return index(rest.empty() || same(rest, u"ES") ? u"es" : u"es-MX");
  if (same(lang, u"pt"))
    return index(same(rest, u"BR") ? u"pt-BR" : u"pt");
  if (same(lang, u"nb") || same(lang, u"nn"))
    return index(u"no");
  for (size_t i = 0; n && i < kCultureCount; ++i)
    if (same(lang, kCultures[i]))
      return i;
  return index(u"en");
}

// When a pass over the table is due: until one has ended, when the language changed since, and when the table no longer
// holds its first entry (holds_first false): the engine collected a table only a Lua LoadAsset held and loaded it again
// without ours [inference: not seen in game].
struct Pass {
  bool filled = false;
  size_t in_culture = 0;
  bool due(size_t now, bool holds_first = true) const { return !filled || now != in_culture || !holds_first; }
  void done(size_t now) { filled = true, in_culture = now; }
};

// The status line. wait: no pass has ended (the table not loaded yet); ready: every entry exists; fault: the first
// fault ended the passes for the run. No line off the pinned build, so Lua waits there too.
enum class State : uint8_t { wait, ready, fault };
inline std::string line(State s, const char *word = "camptext") {
  return std::string(word) + "=" + (s == State::ready ? "ready" : s == State::fault ? "fault" : "wait");
}
